<?php
/**
 * Printable ledger of one account (docs/14).
 *
 * @var string $from
 * @var string $to
 * @var array  $ledger LedgerService::accountLedger()
 */
use App\Services\FinanceService;
use App\Services\LedgerService;

$account = $ledger['account'];
$cents = static fn (int $c): string => $c === 0 ? '' : money(FinanceService::money($c));
$balance = static fn (int $net): string => money(FinanceService::money(abs($net))) . ' ' . LedgerService::side($net);
$cell = 'border border-slate-300 px-2 py-1.5';
?>
<section class="mt-6 space-y-6">
    <div class="flex flex-wrap items-start justify-between gap-4">
        <div>
            <h1 class="font-display text-2xl font-extrabold uppercase tracking-wide text-brand-navy">General Ledger</h1>
            <p class="mt-1 text-lg font-semibold text-brand-navy"><?= e($account['code'] . ' · ' . $account['name']) ?></p>
            <p class="text-sm text-slate-600"><?= e(dt($from . ' 00:00:00', 'F j, Y')) ?> to <?= e(dt($to . ' 00:00:00', 'F j, Y')) ?></p>
        </div>
        <p class="text-right text-xs text-slate-500">Generated by <?= e($user->fullName()) ?></p>
    </div>

    <div class="overflow-x-auto print:overflow-visible">
        <table class="w-full border border-slate-300 text-sm">
            <thead class="bg-brand-50 text-left text-brand-navy">
                <tr>
                    <th scope="col" class="<?= $cell ?>">Date</th>
                    <th scope="col" class="<?= $cell ?>">Ref</th>
                    <th scope="col" class="<?= $cell ?>">Particulars</th>
                    <th scope="col" class="<?= $cell ?> text-right">Debit</th>
                    <th scope="col" class="<?= $cell ?> text-right">Credit</th>
                    <th scope="col" class="<?= $cell ?> text-right">Balance</th>
                </tr>
            </thead>
            <tbody>
                <tr class="bg-slate-50 font-semibold"><td class="<?= $cell ?>"></td><td class="<?= $cell ?>"></td><td class="<?= $cell ?>">Opening balance</td><td class="<?= $cell ?>"></td><td class="<?= $cell ?>"></td><td class="<?= $cell ?> whitespace-nowrap text-right tabular-nums"><?= e($balance($ledger['opening'])) ?></td></tr>
                <?php foreach ($ledger['rows'] as $row): ?>
                    <tr>
                        <td class="<?= $cell ?> whitespace-nowrap"><?= e(d($row['at'])) ?></td>
                        <td class="<?= $cell ?> whitespace-nowrap font-semibold"><?= e($row['ref']) ?></td>
                        <td class="<?= $cell ?>"><?= e($row['particulars']) ?></td>
                        <td class="<?= $cell ?> whitespace-nowrap text-right tabular-nums"><?= e($cents($row['debit'])) ?></td>
                        <td class="<?= $cell ?> whitespace-nowrap text-right tabular-nums"><?= e($cents($row['credit'])) ?></td>
                        <td class="<?= $cell ?> whitespace-nowrap text-right tabular-nums"><?= e($balance($row['balance'])) ?></td>
                    </tr>
                <?php endforeach; ?>
            </tbody>
            <tfoot class="font-semibold">
                <tr>
                    <th scope="row" colspan="3" class="px-2 py-2 text-right">Closing balance</th>
                    <td class="px-2 py-2 text-right tabular-nums"><?= e(money(FinanceService::money($ledger['debit']))) ?></td>
                    <td class="px-2 py-2 text-right tabular-nums"><?= e(money(FinanceService::money($ledger['credit']))) ?></td>
                    <td class="px-2 py-2 text-right tabular-nums"><?= e($balance($ledger['closing'])) ?></td>
                </tr>
            </tfoot>
        </table>
    </div>
</section>
