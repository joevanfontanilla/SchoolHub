    <?php foreach ($report['groups'] as $group): ?>
        <div class="break-inside-avoid-page">
            <h2 class="mb-1 font-display text-base font-bold text-brand-navy"><?= e($group['program'] . ' · ' . $group['year']) ?></h2>
            <div class="overflow-x-auto print:overflow-visible">
