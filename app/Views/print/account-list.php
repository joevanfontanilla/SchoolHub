            <p class="mt-1 text-sm text-slate-600"><?= e($scope) ?> · as of <?= e(dt(date('Y-m-d H:i:s'), 'F j, Y g:i A')) ?></p>
        </div>
        <p class="text-right text-xs text-slate-500">Generated by <?= e($user->fullName()) ?></p>
    </div>

    <dl class="grid grid-cols-4 gap-3 text-sm">
