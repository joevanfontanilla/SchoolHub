<?php
/**
 * Printable trial balance (docs/14).
 *
 * @var string $from
 * @var string $to
 * @var array  $report LedgerService::trialBalance()
 */
use App\Services\FinanceService;
use App\Services\LedgerAccountService;

$money = static fn (int $cents): string => $cents === 0 ? '' : money(FinanceService::money($cents));
$cell = 'border border-slate-300 px-1.5 py-1';
$totals = $report['totals'];
$last = null;
?>
<section class="mt-6 space-y-6">
    <div class="flex flex-wrap items-start justify-between gap-4">
        <div>
            <h1 class="font-display text-2xl font-extrabold uppercase tracking-wide text-brand-navy">Trial Balance</h1>
            <p class="mt-1 text-sm text-slate-600"><?= e(dt($from . ' 00:00:00', 'F j, Y')) ?> to <?= e(dt($to . ' 00:00:00', 'F j, Y')) ?></p>
        </div>
        <p class="text-right text-xs text-slate-500">Generated by <?= e($user->fullName()) ?><br><?= $report['balanced'] ? 'Debits equal credits' : 'OUT OF BALANCE' ?></p>
    </div>

    <div class="overflow-x-auto print:overflow-visible">
        <table class="w-full border border-slate-300 text-xs">
            <thead class="bg-brand-50 text-left text-brand-navy">
                <tr>
                    <th scope="col" class="<?= $cell ?>">Code</th>
                    <th scope="col" class="<?= $cell ?>">Account</th>
                    <th scope="col" class="<?= $cell ?> text-right">Opening Dr</th>
                    <th scope="col" class="<?= $cell ?> text-right">Opening Cr</th>
                    <th scope="col" class="<?= $cell ?> text-right">Debits</th>
                    <th scope="col" class="<?= $cell ?> text-right">Credits</th>
                    <th scope="col" class="<?= $cell ?> text-right">Closing Dr</th>
                    <th scope="col" class="<?= $cell ?> text-right">Closing Cr</th>
                </tr>
            </thead>
            <tbody>
                <?php foreach ($report['rows'] as $row): ?>
                    <?php if ($row['type'] !== $last): $last = $row['type']; ?>
                        <tr class="bg-slate-50"><th scope="colgroup" colspan="8" class="<?= $cell ?> text-left font-semibold uppercase"><?= e(LedgerAccountService::TYPES[$row['type']] ?? $row['type']) ?></th></tr>
                    <?php endif; ?>
                    <tr>
                        <td class="<?= $cell ?>"><?= e($row['code']) ?></td>
                        <td class="<?= $cell ?>"><?= e($row['name']) ?></td>
                        <td class="<?= $cell ?> whitespace-nowrap text-right tabular-nums"><?= e($money(max(0, $row['opening']))) ?></td>
                        <td class="<?= $cell ?> whitespace-nowrap text-right tabular-nums"><?= e($money(max(0, -$row['opening']))) ?></td>
                        <td class="<?= $cell ?> whitespace-nowrap text-right tabular-nums"><?= e($money($row['debit'])) ?></td>
                        <td class="<?= $cell ?> whitespace-nowrap text-right tabular-nums"><?= e($money($row['credit'])) ?></td>
                        <td class="<?= $cell ?> whitespace-nowrap text-right font-semibold tabular-nums"><?= e($money(max(0, $row['closing']))) ?></td>
                        <td class="<?= $cell ?> whitespace-nowrap text-right font-semibold tabular-nums"><?= e($money(max(0, -$row['closing']))) ?></td>
                    </tr>
                <?php endforeach; ?>
            </tbody>
            <tfoot class="font-semibold">
                <tr>
                    <th scope="row" colspan="2" class="px-1.5 py-2 text-right">Totals</th>
                    <td class="px-1.5 py-2 text-right tabular-nums"><?= e(money(FinanceService::money($totals['openingDr']))) ?></td>
                    <td class="px-1.5 py-2 text-right tabular-nums"><?= e(money(FinanceService::money($totals['openingCr']))) ?></td>
                    <td class="px-1.5 py-2 text-right tabular-nums"><?= e(money(FinanceService::money($totals['debit']))) ?></td>
                    <td class="px-1.5 py-2 text-right tabular-nums"><?= e(money(FinanceService::money($totals['credit']))) ?></td>
                    <td class="px-1.5 py-2 text-right tabular-nums"><?= e(money(FinanceService::money($totals['closingDr']))) ?></td>
                    <td class="px-1.5 py-2 text-right tabular-nums"><?= e(money(FinanceService::money($totals['closingCr']))) ?></td>
                </tr>
            </tfoot>
        </table>
    </div>
</section>
